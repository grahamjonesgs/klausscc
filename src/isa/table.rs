//! The built-in ISA-encoding-v2 opcode table.

use super::{Opcode, Operand};

/// An [`Opcode`] from its mnemonic, v2 template word and operand layout,
/// with no docs section or description.
const fn op(name: &'static str, template: u32, ops: &'static [Operand]) -> Opcode {
    Opcode {
        name,
        template,
        ops,
        section: "",
        doc: "",
    }
}

